CREATE TABLE usuario (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome       VARCHAR(120) NOT NULL,
    email      VARCHAR(160) NOT NULL,
    senha_hash VARCHAR(100) NOT NULL,
    papel      VARCHAR(20)  NOT NULL,
    CONSTRAINT uk_usuario_email UNIQUE (email)
);

CREATE TABLE chamado (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo         VARCHAR(160)  NOT NULL,
    descricao      VARCHAR(4000) NOT NULL,
    categoria      VARCHAR(20)   NOT NULL,
    prioridade     VARCHAR(20)   NOT NULL,
    status         VARCHAR(30)   NOT NULL,
    solicitante_id BIGINT        NOT NULL,
    tecnico_id     BIGINT,
    criado_em      TIMESTAMP WITH TIME ZONE NOT NULL,
    atualizado_em  TIMESTAMP WITH TIME ZONE NOT NULL,
    resolvido_em   TIMESTAMP WITH TIME ZONE,
    prazo_sla      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_chamado_solicitante FOREIGN KEY (solicitante_id) REFERENCES usuario (id),
    CONSTRAINT fk_chamado_tecnico FOREIGN KEY (tecnico_id) REFERENCES usuario (id)
);

CREATE INDEX idx_chamado_status ON chamado (status);
CREATE INDEX idx_chamado_solicitante ON chamado (solicitante_id);
CREATE INDEX idx_chamado_prazo_sla ON chamado (prazo_sla);

CREATE TABLE comentario (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chamado_id BIGINT         NOT NULL,
    autor_id   BIGINT         NOT NULL,
    texto      VARCHAR(2000)  NOT NULL,
    criado_em  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_comentario_chamado FOREIGN KEY (chamado_id) REFERENCES chamado (id) ON DELETE CASCADE,
    CONSTRAINT fk_comentario_autor FOREIGN KEY (autor_id) REFERENCES usuario (id)
);

CREATE INDEX idx_comentario_chamado ON comentario (chamado_id);
